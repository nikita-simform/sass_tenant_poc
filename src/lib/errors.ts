// Typed application errors. Route handlers throw these; errorHandler.ts maps
// them to a consistent JSON shape. Anything else (a real bug) becomes a safe
// generic 500 — see lib/middleware/errorHandler.ts.
export class AppError extends Error {
  constructor(
    message: string,
    public readonly status: number,
    public readonly code: string,
  ) {
    super(message);
    this.name = new.target.name;
  }
}

export class ValidationError extends AppError {
  constructor(message: string) {
    super(message, 400, "VALIDATION_ERROR");
  }
}

export class UnauthorizedError extends AppError {
  constructor(message = "Authentication required") {
    super(message, 401, "UNAUTHORIZED");
  }
}

export class ForbiddenError extends AppError {
  constructor(message = "Not allowed to perform this action") {
    super(message, 403, "FORBIDDEN");
  }
}

export class NotFoundError extends AppError {
  constructor(message = "Resource not found") {
    super(message, 404, "NOT_FOUND");
  }
}

export class LimitExceededError extends AppError {
  constructor(message: string) {
    super(message, 409, "LIMIT_EXCEEDED");
  }
}
