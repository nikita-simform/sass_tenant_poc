import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";

const MIGRATIONS_DIR = path.join(process.cwd(), "prisma", "tenant-schema", "migrations");

export type TenantMigrationFile = { name: string; sql: string };

export function listTenantMigrationFiles(): TenantMigrationFile[] {
  const dirNames = readdirSync(MIGRATIONS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort(); // Prisma names these like 20240101000000_init — lexicographic order is chronological order.

  return dirNames.map((name) => ({
    name,
    sql: readFileSync(path.join(MIGRATIONS_DIR, name, "migration.sql"), "utf-8"),
  }));
}

// NOT a general-purpose SQL splitter — only safe because these files are
// 100% generated by `prisma migrate dev` for a plain CREATE TABLE/INDEX/ALTER
// TABLE model (see prisma/tenant-schema/schema.prisma), which never embeds a
// semicolon inside a string or dollar-quoted body. Do not reuse this for
// hand-written or arbitrary SQL.
export function splitGeneratedMigrationStatements(sql: string): string[] {
  return sql
    .split(";")
    .map((statement) => statement.trim())
    .filter((statement) => statement.length > 0);
}

// Defensive check before a schema name is interpolated into DDL (CREATE
// SCHEMA / SET search_path) — every schema name must pass this regardless of
// how it was produced. deriveSchemaName() below is the only place user input
// is allowed to influence a schema name, and it re-validates its own output
// against this same check before returning.
export function assertSafeSchemaName(schemaName: string): void {
  if (!/^[a-z][a-z0-9_]*$/.test(schemaName) || schemaName.length > 63) {
    throw new Error(`Refusing to use unsafe schema name: ${schemaName}`);
  }
}

const SCHEMA_NAME_PREFIX = "org_";
const MAX_SCHEMA_NAME_LENGTH = 63; // Postgres identifier limit

// Turns a user-supplied organization name into a readable, safe Postgres
// schema name — e.g. "Acme Corp!" -> "org_acme_corp". This is the ONLY place
// user-controlled text is allowed to influence a schema name: everything
// outside [a-z0-9] is stripped or collapsed to "_", and the result is
// re-validated by assertSafeSchemaName before ever being interpolated into
// DDL. Organization.name has a DB-level unique constraint (see
// onboarding.ts), so in practice this also ends up unique — but see
// onboarding.ts for what happens in the rare case two different names
// happen to slugify identically.
export function deriveSchemaName(organizationName: string): string {
  const normalized = organizationName
    .normalize("NFKD")
    .replace(/\p{Diacritic}/gu, "") // strip accents: "é" -> "e"
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");

  const maxSlugLength = MAX_SCHEMA_NAME_LENGTH - SCHEMA_NAME_PREFIX.length;
  const slug = (normalized || "org").slice(0, maxSlugLength).replace(/_+$/, "") || "org";

  const schemaName = `${SCHEMA_NAME_PREFIX}${slug}`;
  assertSafeSchemaName(schemaName);
  return schemaName;
}
